/** Root of the installed @openfleet-tools/cli package (contains package.json, core/, dist/). */
export function packageRoot(): string {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
}

export function packageVersion(): string {
  return readJson<{ version: string }>(path.join(packageRoot(), "package.json")).version;
}

export function installedCoreVersion(ws: Workspace): string | undefined {
  try {
    return fs.readFileSync(path.join(ws.core, "VERSION"), "utf8").trim();
  } catch {
    return undefined;
  }
}

const AGENT_PREFIX = "openfleet-";
const MAX_AGENT_PROMPT = 30_000;

/**
 * Replace `<ws>/core` with the assets shipped in this package plus
 * a copy of the compiled library (used by hooks), then regenerate agents.
 */
export function installCore(ws: Workspace, warn: (msg: string) => void = () => {}): CoreIndex {
  const pkg = packageRoot();
  const version = packageVersion();
  const tmp = `${ws.core}.tmp-${process.pid}`;
  fs.rmSync(tmp, { recursive: true, force: true });
  copyDir(path.join(pkg, "core"), tmp);
  copyDir(path.join(pkg, "dist"), path.join(tmp, "lib"), (rel) => rel.endsWith(".d.ts") || rel.endsWith(".map"));
  writeJson(path.join(tmp, "package.json"), { name: "openfleet-core", private: true, type: "module", version });
  fs.writeFileSync(path.join(tmp, "VERSION"), version + "\n");
  fs.writeFileSync(
    path.join(tmp, "DO_NOT_EDIT.md"),
    "# Generated by @openfleet-tools/cli\n\nThis folder is fully replaced by `npx openfleet update`. Do not edit it.\n" +
      "Customize OpenFleet with extensions in `extensions/` instead.\n",
  );
  const pluginFile = path.join(tmp, "plugin.json");
  const plugin = { ...readJson<Record<string, unknown>>(pluginFile), version };
  writeJson(pluginFile, plugin);
  const claude = path.join(tmp, "claude");
  writeJson(path.join(claude, ".claude-plugin", "plugin.json"), claudePluginManifest(plugin));
  writeJson(path.join(claude, "hooks", "hooks.json"), claudeHooks());
  // Skills hold host blocks: render Claude's copy first, then Copilot's in place.
  renderSkills(path.join(tmp, "skills"), path.join(claude, "skills"), "claude");
  renderSkills(path.join(tmp, "skills"), path.join(tmp, "skills"), "copilot");
  fs.rmSync(ws.core, { recursive: true, force: true });
  fs.renameSync(tmp, ws.core);
  return syncExtensions(ws, warn);
}

function renderSkills(src: string, dest: string, host: Host): void {
  for (const rel of fs.readdirSync(src, { recursive: true, encoding: "utf8" })) {
    const from = path.join(src, rel);
    if (!fs.statSync(from).isFile()) continue;
    const text = fs.readFileSync(from, "utf8");
    writeFileAtomic(path.join(dest, rel), rel.endsWith(".md") ? renderForHost(text, host) : text);
  }
}

/** File name and content of an agent for a host, from its Copilot-format source. */
function hostAgent(host: Host, name: string, copilotAgent: string): [string, string] {
  return host === "claude" ? [`${name}.md`, toClaudeAgent(copilotAgent)] : [`${name}.agent.md`, copilotAgent];
}

function frontmatter(fields: Record<string, unknown>): string {
  const lines = Object.entries(fields).map(([k, v]) => `${k}: ${JSON.stringify(v)}`);
  return `---\n${lines.join("\n")}\n---\n`;
}

function readMd(ext: LoadedExtension, rel: string): string {
  return fs.readFileSync(path.join(ext.dir, rel), "utf8").trim();
}

/** Agent used by an extension's CLI commands. */
export function commandAgentName(ext: string): string {
  return `${AGENT_PREFIX}ext-${ext}`;
}

const REPORT_PROTOCOL = [
  "## Report",
  "",
  "End your final reply with exactly one fenced block:",
  "",
  "````",
  "```openfleet-report",
  '{"status": "done" | "failed", "summary": "…", "outputs": {"<key>": "<string>"}, "followUps": ["…"]}',
  "```",
  "````",
  "",
  "- `outputs` (optional): flat string values only. OpenFleet records them on the child and injects them into the",
  "  prompts of every child that depends on it. An output named `prUrl` marks the pull request you opened for this",
  "  child; finalize then updates that PR instead of opening a new one.",
  "- `followUps` (optional): short reminders for people after the run. They are listed in the run summary and in",
  "  the child's PR body.",
].join("\n");

function phaseAgentBody(ext: LoadedExtension, entry: PhaseEntry, settings: string): string {
  const m = ext.manifest;
  const perms = permissionsOf(m);
  const facts = [
    `- slot: \`${entry.slot}\``,
    `- blocking: ${entry.blocking ? "yes. If you fail, the child fails" : "no (advisory)"}`,
    `- time limit: ${entry.timeoutMinutes ?? DEFAULT_TIMEOUT_MINUTES} minutes`,
    entry.when ? `- runs only when one of these exists: ${entry.when.files.map((f) => `\`${f}\``).join(", ")}` : "",
  ].filter(Boolean);
  return [
    `You are the OpenFleet extension **${m.name}**, running in the \`${entry.slot}\` phase slot.`,
    "",
    ...facts,
    "",
    `Declared permissions: ${perms.join(", ")}. Do not attempt actions outside these permissions.`,
    "The OpenFleet workspace is the current working directory; project data lives in `projects/<name>/`",
    "(spec.md, state.json, events.jsonl, contracts/). Treat events.jsonl as append-only and never edit it.",
    "The coordinator's prompt names the project and, for per-child slots, the child id and its worktree.",
    "",
    REPORT_PROTOCOL,
    settings ? `\n${settings}` : "",
    "",
    readMd(ext, entry.instructions),
  ].join("\n");
}

function commandAgentBody(m: ExtensionManifest, settings: string): string {
  return [
    `You are the OpenFleet extension **${m.name}**, running one of its CLI commands.`,
    "",
    `Declared permissions: ${permissionsOf(m).join(", ")}. Do not attempt actions outside these permissions.`,
    "The OpenFleet workspace is the current working directory; project data lives in `projects/<name>/`",
    "(spec.md, state.json, events.jsonl, contracts/). Treat events.jsonl as append-only and never edit it.",
    "When you finish, reply with a concise summary of what you produced.",
    settings ? `\n${settings}` : "",
  ].join("\n");
}

/**
 * Regenerate everything in core that depends on installed extensions:
 * role agents (template + augment instructions), one agent per phase entry,
 * a command agent and skills per extension with commands, and `extensions.json`.
 */
export function syncExtensions(ws: Workspace, warn: (msg: string) => void = () => {}): CoreIndex {
  const coreVersion = installedCoreVersion(ws) ?? packageVersion();
  const exts = loadExtensions(ws, warn);
  const config = readExtensionsConfig(ws);
  const installed = new Set(exts.map((e) => e.manifest.name));
  for (const name of Object.keys(config)) {
    if (!installed.has(name)) warn(`extensions.config.json has settings for "${name}", which is not installed.`);
  }
  const resolved = new Map(exts.map((e) => [e.manifest.name, resolveSettings(e.manifest, config)]));
  const sections = new Map(
    exts.map((e) => [e.manifest.name, settingsSection(e.manifest, resolved.get(e.manifest.name)!)]),
  );
  const templates = path.join(ws.core, "templates", "agents");
  const dirs = HOSTS.map((host) => {
    const root = pluginDir(ws, host);
    return { host, agents: path.join(root, "agents"), skills: path.join(root, "skills") };
  });
  for (const d of dirs) {
    fs.rmSync(d.agents, { recursive: true, force: true });
    fs.mkdirSync(d.agents, { recursive: true });
    for (const entry of fs.existsSync(d.skills) ? fs.readdirSync(d.skills) : []) {
      if (entry.startsWith(`${AGENT_PREFIX}ext-`))
        fs.rmSync(path.join(d.skills, entry), { recursive: true, force: true });
    }
  }
  /** Write one agent (Copilot format) for every host it applies to. */
  const writeAgent = (name: string, copilotAgent: (host: Host) => string, hosts?: readonly Host[]) => {
    for (const d of dirs.filter((x) => !hosts || hosts.includes(x.host))) {
      const [file, content] = hostAgent(d.host, name, copilotAgent(d.host));
      writeFileAtomic(path.join(d.agents, file), content);
    }
  };
  const writeSkill = (name: string, content: string) => {
    for (const d of dirs) writeFileAtomic(path.join(d.skills, name, "SKILL.md"), content);
  };

  const index: CoreIndex = {
    v: 2,
    coreVersion,
    slots: Object.fromEntries(SLOTS.map((s) => [s, []])) as unknown as CoreIndex["slots"],
    augments: Object.fromEntries(ROLES.map((r) => [r, []])) as unknown as CoreIndex["augments"],
    commands: {},
    settings: Object.fromEntries(
      exts
        .filter((e) => Object.keys(e.manifest.settings ?? {}).length)
        .map((e) => [e.manifest.name, resolved.get(e.manifest.name)!]),
    ),
  };

  for (const role of ROLES) {
    const name = `${AGENT_PREFIX}${role}`;
    const template = fs.readFileSync(path.join(templates, `${name}.agent.md`), "utf8");
    const augmentText = (host: Host) => {
      let text = "";
      for (const ext of exts) {
        const augments = (ext.manifest.augments ?? []).filter((a) => a.role === role && forHost(a, host));
        if (!augments.length) continue;
        const parts = augments.map((a) => readMd(ext, a.instructions));
        const settings = sections.get(ext.manifest.name)!.replace(/^## Settings/, "### Settings");
        text += `\n## Extension: ${ext.manifest.name}\n\n${parts.join("\n\n")}\n${settings ? `\n${settings}\n` : ""}`;
      }
      return text;
    };
    for (const ext of exts) {
      if ((ext.manifest.augments ?? []).some((a) => a.role === role)) index.augments[role].push(ext.manifest.name);
    }
    const body = (host: Host) => renderForHost(template, host).trimEnd() + "\n" + augmentText(host);
    const copilot = body("copilot");
    if (copilot.length > MAX_AGENT_PROMPT) {
      warn(
        `Agent ${name}.agent.md is ${copilot.length} chars (Copilot limit ${MAX_AGENT_PROMPT}); augment extensions may be truncated.`,
      );
    }
    writeAgent(name, body);
  }

  for (const ext of exts) {
    const m = ext.manifest;
    const tools = toolsFor(permissionsOf(m));
    const settings = sections.get(m.name)!;
    const names = phaseAgentNames(m);
    (m.phases ?? []).forEach((entry, i) => {
      const agent = names[i]!;
      const header = frontmatter({
        name: agent,
        description: `${m.description ?? `OpenFleet extension ${m.name}`} (${entry.slot} phase)`,
        tools,
      });
      const content = header + phaseAgentBody(ext, entry, settings).trimEnd() + "\n";
      writeAgent(agent, () => content, entry.hosts);
      index.slots[entry.slot].push({
        extension: m.name,
        agent: qualifiedAgentName(agent),
        blocking: entry.blocking ?? false,
        ...(entry.when ? { when: { files: [...entry.when.files] } } : {}),
        timeoutMinutes: entry.timeoutMinutes ?? DEFAULT_TIMEOUT_MINUTES,
        ...(entry.hosts ? { hosts: [...entry.hosts] } : {}),
      });
    });
    const commands = Object.entries(m.commands ?? {});
    if (!commands.length) continue;
    const agent = commandAgentName(m.name);
    const content =
      frontmatter({ name: agent, description: m.description ?? `OpenFleet extension ${m.name}`, tools }) +
      commandAgentBody(m, settings).trimEnd() +
      "\n";
    writeAgent(agent, () => content);
    for (const [cmd, rel] of commands) {
      if (index.commands[cmd]) {
        warn(`Command "${cmd}" from extension "${m.name}" shadows "${index.commands[cmd].extension}"; ignoring.`);
        continue;
      }
      const skill = `${AGENT_PREFIX}ext-${m.name}-${cmd}`;
      writeSkill(
        skill,
        frontmatter({ name: skill, description: `OpenFleet extension ${m.name}: \`openfleet ${cmd}\` command.` }) +
          "\n" +
          readMd(ext, rel) +
          "\n" +
          (settings ? `\n${settings}\n` : ""),
      );
      index.commands[cmd] = { extension: m.name, agent: qualifiedAgentName(agent), skill };
    }
  }

  writeJson(path.join(ws.core, "extensions.json"), index);
  return index;
}
