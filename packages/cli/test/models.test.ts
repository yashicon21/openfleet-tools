import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { modelFor, readConfig, setConfig } from "../src/config.js";
import { syncExtensions } from "../src/core.js";
import { readJson } from "../src/fsutil.js";
import { parseFrontmatter, pluginDir, type Host } from "../src/hosts.js";
import { buildClaudeArgs, buildCopilotArgs } from "../src/launcher.js";
import { tmpDir, workspace, writeExtension } from "./helpers.js";

const BIN = fileURLToPath(new URL("../dist/bin.js", import.meta.url));

function cli(cwd: string, args: string[]) {
  const r = spawnSync(process.execPath, [BIN, ...args], { cwd, encoding: "utf8" });
  return { code: r.status, stdout: r.stdout, stderr: r.stderr };
}

/** The `model` frontmatter value of a generated agent, or undefined. */
function agentModel(ws: ReturnType<typeof workspace>, host: Host, name: string): string | undefined {
  const file = path.join(pluginDir(ws, host), "agents", host === "claude" ? `${name}.md` : `${name}.agent.md`);
  const raw = parseFrontmatter(fs.readFileSync(file, "utf8")).fields.find(([k]) => k === "model")?.[1];
  return raw === undefined ? undefined : (JSON.parse(raw) as string);
}

describe("models per role", () => {
  it("uses one default for every role, or a model per role, per host", () => {
    const ws = workspace();
    expect(cli(ws.root, ["config", "set", "models.claude.default", "sonnet"]).code).toBe(0);
    expect(cli(ws.root, ["config", "set", "models.claude.implementer", "claude-opus-5-5"]).code).toBe(0);
    expect(cli(ws.root, ["config", "set", "models.claude.tester", "haiku"]).code).toBe(0);
    expect(cli(ws.root, ["config", "set", "models.copilot.planner", "Claude Sonnet 5.5"]).code).toBe(0);
    expect(readJson<{ models: object }>(ws.marker).models).toEqual({
      claude: { default: "sonnet", implementer: "claude-opus-5-5", tester: "haiku" },
      copilot: { planner: "Claude Sonnet 5.5" },
    });
    // Agents are regenerated by `config set`; Claude model ids are written as given, not shortened.
    expect(agentModel(ws, "claude", "openfleet-implementer")).toBe("claude-opus-5-5");
    expect(agentModel(ws, "claude", "openfleet-tester")).toBe("haiku");
    expect(agentModel(ws, "claude", "openfleet-planner")).toBe("sonnet");
    expect(agentModel(ws, "claude", "openfleet-coordinator")).toBe("sonnet");
    expect(agentModel(ws, "copilot", "openfleet-planner")).toBe("Claude Sonnet 5.5");
    expect(agentModel(ws, "copilot", "openfleet-implementer")).toBeUndefined();
    const config = readConfig(ws);
    expect(modelFor(config, "claude", "repo-coordinator")).toBe("sonnet");
    expect(modelFor(config, "copilot", "tester")).toBeUndefined();
  });

  it('removes a model with "" and validates hosts, roles and names', () => {
    const ws = workspace();
    setConfig(ws, "models.claude.tester", "haiku");
    expect(cli(ws.root, ["config", "set", "models.claude.tester", ""]).code).toBe(0);
    expect(readJson<Record<string, unknown>>(ws.marker).models).toBeUndefined();
    expect(agentModel(ws, "claude", "openfleet-tester")).toBeUndefined();
    expect(() => setConfig(ws, "models.gemini.tester", "x")).toThrow(/unknown host "gemini"/);
    expect(() => setConfig(ws, "models.claude.reviewer", "x")).toThrow(/unknown key "reviewer"/);
    expect(() => setConfig(ws, "models.claude", "x")).toThrow(/Use: npx openfleet config set models\./);
    expect(() => setConfig(ws, "models.claude.tester", "bad;name")).toThrow(/must be a model name/);
    expect(() => setConfig(ws, "models", "x")).toThrow();
  });

  it("gives extension agents the extensions model, falling back to default", () => {
    const ws = workspace();
    const src = writeExtension(path.join(tmpDir(), "audit"), {
      manifest: 2,
      name: "audit",
      version: "1.0.0",
      core: ">=0.0.0",
      phases: [{ slot: "post-run", instructions: "instructions.md" }],
    });
    expect(cli(ws.root, ["add", src]).code).toBe(0);
    setConfig(ws, "models.claude.default", "sonnet");
    syncExtensions(ws);
    const ext = fs.readdirSync(path.join(pluginDir(ws, "claude"), "agents")).find((f) => f.includes("ext-audit"));
    expect(ext).toBeDefined();
    expect(agentModel(ws, "claude", ext!.replace(/\.md$/, ""))).toBe("sonnet");
    setConfig(ws, "models.claude.extensions", "haiku");
    syncExtensions(ws);
    expect(agentModel(ws, "claude", ext!.replace(/\.md$/, ""))).toBe("haiku");
  });

  it("passes the coordinator model as --model at launch, unless the user passed one", () => {
    const ws = workspace();
    setConfig(ws, "models.claude.coordinator", "opus");
    setConfig(ws, "models.copilot.default", "gpt-5");
    const base = { ws, agent: "openfleet-coordinator", prompt: "go" };
    const claude = buildClaudeArgs({ ...base, host: "claude" });
    expect(claude[claude.indexOf("--model") + 1]).toBe("opus");
    const copilot = buildCopilotArgs({ ...base, host: "copilot" });
    expect(copilot[copilot.indexOf("--model") + 1]).toBe("gpt-5");
    const own = buildClaudeArgs({ ...base, host: "claude", passthrough: ["--model", "haiku"] });
    expect(own.filter((a) => a === "--model")).toHaveLength(1);
    expect(own.at(-1)).toBe("haiku");
    const none = workspace();
    expect(buildClaudeArgs({ ...base, ws: none, host: "claude" })).not.toContain("--model");
  });
});

describe("models in the run report", () => {
  it("logs the configured models at launch and shows them next to the models used", () => {
    const ws = workspace();
    setConfig(ws, "models.copilot.default", "gpt-5");
    setConfig(ws, "models.copilot.tester", "gpt-5-mini");
    const dir = tmpDir();
    const bin = path.join(dir, "fake-copilot.mjs");
    fs.writeFileSync(bin, "#!/usr/bin/env node\n");
    fs.chmodSync(bin, 0o755);
    const home = tmpDir();
    const env = { ...process.env, OPENFLEET_COPILOT_BIN: bin, COPILOT_HOME: home };
    const run = (args: string[]) =>
      spawnSync(process.execPath, [BIN, ...args], { cwd: ws.root, encoding: "utf8", env });
    expect(run(["new", "p", "Do", "it"]).status).toBe(0);
    const statePath = path.join(ws.projects, "p", "state.json");
    const sessionId = readJson<{ sessionId: string }>(statePath).sessionId;
    const events = fs.readFileSync(path.join(ws.projects, "p", "events.jsonl"), "utf8");
    expect(events).toContain('"type":"models.configured"');
    expect(events).toContain('"tester":"gpt-5-mini"');
    const transcript = path.join(home, "session-state", sessionId);
    fs.mkdirSync(transcript, { recursive: true });
    const usage = (id: string, model: string, tokens: number, agentId?: string) => ({
      type: "session.usage_record",
      ...(agentId ? { agentId } : {}),
      data: { usage: { apiCallId: id, model, inputTokens: tokens, outputTokens: 0 } },
    });
    fs.writeFileSync(
      path.join(transcript, "events.jsonl"),
      [
        usage("c1", "gpt-5", 1000),
        { type: "subagent.started", agentId: "a1", data: { agentName: "openfleet:openfleet-tester" } },
        usage("t1", "gpt-5-mini", 400, "a1"),
      ]
        .map((l) => JSON.stringify(l))
        .join("\n") + "\n",
    );
    const out = path.join(tmpDir(), "r.html");
    expect(run(["report", "p", "--out", out]).status).toBe(0);
    const html = fs.readFileSync(out, "utf8");
    expect(html).toContain("<h3>Models by role</h3>");
    expect(html).toMatch(
      /<td>Top coordinator<\/td><td><code>gpt-5<\/code><\/td><td><code>gpt-5<\/code> \(1\.0k\)<\/td>/,
    );
    expect(html).toMatch(
      /<td>Testers<\/td><td><code>gpt-5-mini<\/code><\/td><td><code>gpt-5-mini<\/code> \(400\)<\/td>/,
    );
    expect(html).toMatch(/<td>Implementers<\/td><td><code>gpt-5<\/code><\/td><td>—<\/td>/);
  });
});
